// One representative variant per family (exercises the shuffle path AND the
// smem path where the family has two modes).
struct CompileCase {
  const char *family;
  std::int64_t rows;
  std::int64_t cols;
  int block;
  int vec;
  ElemMode mode;
  const char *tag;
};

const CompileCase kCompileCases[] = {
    // bias_gelu: vec 2 and vec 4 (elementwise, mode unused)
    {"bias_gelu", 64, 512, 256, 2, ElemMode::kOnePass, "bg_v2"},
    {"bias_gelu", 128, 256, 128, 4, ElemMode::kOnePass, "bg_v4"},
    // softmax: onepass (warp-shuffle) + twopass (smem tree), row 2048
    {"softmax", 32, 512, 256, 2, ElemMode::kOnePass, "sm_op"},
    {"softmax", 16, 2048, 512, 4, ElemMode::kTwoPass, "sm_tp"},
    // layernorm: onepass (sum/sumsq) + twopass (mean then variance)
    {"layernorm", 32, 512, 256, 2, ElemMode::kOnePass, "ln_op"},
    {"layernorm", 32, 1024, 256, 4, ElemMode::kTwoPass, "ln_tp"},
    // reduction: strided (shuffle combine) + tree (smem halving tree)
    {"reduction", 128, 512, 256, 2, ElemMode::kStrided, "rd_st"},
    {"reduction", 64, 1024, 512, 4, ElemMode::kTree, "rd_tr"},
};

std::string emit_and_compile(const CompileCase &cc, const char *compiler_tag,
                             bool nvcc_compile) {
  const ElemProblem prob = problem(cc.rows, cc.cols, "gfx1101");
  const std::string dir = make_workdir(compiler_tag);
  std::string symbol;
  std::string err;
  std::string src;
  if (std::string(cc.family) == "bias_gelu") {
    BiasGeluConfig cfg;
    cfg.block = cc.block;
    cfg.vec_width = cc.vec;
    symbol = kernel_symbol(cfg);
    src = dir + "/" + symbol + ".hip";
    EXPECT_TRUE(generate_to_file(cfg, prob, src, &err)) << err;
  } else if (std::string(cc.family) == "softmax") {
    SoftmaxConfig cfg;
    cfg.block = cc.block;
    cfg.vec_width = cc.vec;
    cfg.mode = cc.mode;
    symbol = kernel_symbol(cfg);
    src = dir + "/" + symbol + ".hip";
    EXPECT_TRUE(generate_to_file(cfg, prob, src, &err)) << err;
  } else if (std::string(cc.family) == "layernorm") {
    LayerNormConfig cfg;
    cfg.block = cc.block;
    cfg.vec_width = cc.vec;
    cfg.mode = cc.mode;
    symbol = kernel_symbol(cfg);
    src = dir + "/" + symbol + ".hip";
    EXPECT_TRUE(generate_to_file(cfg, prob, src, &err)) << err;
  } else {  // reduction
    ReductionConfig cfg;
    cfg.block = cc.block;
    cfg.vec_width = cc.vec;
    cfg.mode = cc.mode;
    symbol = kernel_symbol(cfg);
    src = dir + "/" + symbol + ".hip";
    EXPECT_TRUE(generate_to_file(cfg, prob, src, &err)) << err;
  }
  std::string out;
  if (nvcc_compile) {
    out = dir + "/" + symbol + ".o";
    std::string log;
    const int rc = run_command(dir, nvcc_cmd(src, out, "sm_80"), &log);
    std::cout << "[nvcc sm_80] " << symbol << " rc=" << rc << "\n" << log;
    EXPECT_EQ(rc, 0) << "nvcc sm_80 compile gate failed";
    const int rc90 = run_command(dir, nvcc_cmd(src, dir + "/" + symbol + "_90.o",
                                               "sm_90"), &log);
    std::cout << "[nvcc sm_90] " << symbol << " rc=" << rc90 << "\n" << log;
    EXPECT_EQ(rc90, 0) << "nvcc sm_90 compile gate failed";
  } else {
    out = dir + "/" + symbol + ".hsaco";
    std::string log;
    const int rc = run_command(dir, hipcc_cmd(src, out), &log);
    std::cout << "[hipcc --genco gfx1101] " << symbol << " rc=" << rc << "\n"
              << log;
    EXPECT_EQ(rc, 0) << "hipcc gfx1101 genco gate failed";
  }
  return out;
}

