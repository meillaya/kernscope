ElemProblem problem(std::int64_t rows, std::int64_t cols,
                    const std::string &arch = "gfx1101") {
  ElemProblem prob;
  prob.rows = rows;
  prob.cols = cols;
  prob.arch = arch;
  prob.dtype_bytes = 2;
  return prob;
}

std::string read_file(const std::string &path) {
  std::ifstream fh(path, std::ios::binary);
  std::ostringstream ss;
  ss << fh.rdbuf();
  return ss.str();
}

int run_command(const std::string &dir, const std::string &cmd,
                std::string *log) {
  const std::string log_path = dir + "/cmd.log";
  const std::string full = "cd " + dir + " && " + cmd + " > cmd.log 2>&1";
  const int status = std::system(full.c_str());
  *log = read_file(log_path);
  if (status == -1)
    return -1;
  if (!WIFEXITED(status))
    return -1;
  return WEXITSTATUS(status);
}

std::string make_workdir(const char *tag) {
  static int counter = 0;
  std::string dir = testing::TempDir() + "/tune_elem_gen_" + tag + "_" +
                    std::to_string(::getpid()) + "_" + std::to_string(++counter);
  std::error_code ec;
  std::filesystem::create_directories(dir, ec);
  EXPECT_FALSE(ec) << "cannot create workdir " << dir;
  return dir;
}

template <typename Config, typename SymbolFn, typename GenFn>
std::string emit_kernel(const Config &cfg, const ElemProblem &prob,
                        SymbolFn symbol_fn, GenFn gen_fn,
                        const std::string &dir) {
  std::string src_path = dir + "/" + symbol_fn(cfg) + ".hip";
  std::string err;
  if (!gen_fn(cfg, prob, src_path, &err)) {
    ADD_FAILURE() << "generate_to_file: " << err;
    return "";
  }
  return src_path;
}

std::string hipcc_cmd(const std::string &src, const std::string &out) {
  std::ostringstream cmd;
  cmd << kHipcc << " --genco --offload-arch=gfx1101 -gline-tables-only "
      << "-D__HIP_PLATFORM_AMD__=1 -I" << kHipInclude << " -I"
      << kKernelTraitsInclude << " " << src << " -o " << out;
  return cmd.str();
}

