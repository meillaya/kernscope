// --- gpu-amd: live golden gates on gfx1101 ---------------------------------

struct LiveCase {
  const char *family;
  std::int64_t rows;
  std::int64_t cols;
  int block;
  int vec;
  ElemMode mode;
  const char *tag;
};

void run_live_gate(const LiveCase &lc) {
  ASSERT_FALSE(kHipcc.empty()) << "hipcc not found at configure time";
  ASSERT_FALSE(kRunner.empty()) << "kernscope_templates_hip_runner target "
                                   "missing (kernels/templates)";
  const ElemProblem prob = problem(lc.rows, lc.cols, "gfx1101");
  const std::string dir = make_workdir(lc.tag);

  std::string symbol;
  std::string src;
  std::string err;
  if (std::string(lc.family) == "bias_gelu") {
    BiasGeluConfig cfg;
    cfg.block = lc.block;
    cfg.vec_width = lc.vec;
    ASSERT_TRUE(validate_config(cfg, prob).valid)
        << validate_config(cfg, prob).reason;
    symbol = kernel_symbol(cfg);
    ASSERT_TRUE(generate_to_file(cfg, prob, dir + "/" + symbol + ".hip", &err))
        << err;
    src = dir + "/" + symbol + ".hip";
  } else if (std::string(lc.family) == "softmax") {
    SoftmaxConfig cfg;
    cfg.block = lc.block;
    cfg.vec_width = lc.vec;
    cfg.mode = lc.mode;
    ASSERT_TRUE(validate_config(cfg, prob).valid)
        << validate_config(cfg, prob).reason;
    symbol = kernel_symbol(cfg);
    ASSERT_TRUE(generate_to_file(cfg, prob, dir + "/" + symbol + ".hip", &err))
        << err;
    src = dir + "/" + symbol + ".hip";
  } else if (std::string(lc.family) == "layernorm") {
    LayerNormConfig cfg;
    cfg.block = lc.block;
    cfg.vec_width = lc.vec;
    cfg.mode = lc.mode;
    ASSERT_TRUE(validate_config(cfg, prob).valid)
        << validate_config(cfg, prob).reason;
    symbol = kernel_symbol(cfg);
    ASSERT_TRUE(generate_to_file(cfg, prob, dir + "/" + symbol + ".hip", &err))
        << err;
    src = dir + "/" + symbol + ".hip";
  } else {  // reduction
    ReductionConfig cfg;
    cfg.block = lc.block;
    cfg.vec_width = lc.vec;
    cfg.mode = lc.mode;
    ASSERT_TRUE(validate_config(cfg, prob).valid)
        << validate_config(cfg, prob).reason;
    symbol = kernel_symbol(cfg);
    ASSERT_TRUE(generate_to_file(cfg, prob, dir + "/" + symbol + ".hip", &err))
        << err;
    src = dir + "/" + symbol + ".hip";
  }

  const std::string hsaco = dir + "/" + lc.tag + ".hsaco";
  std::string log;
  const int compile_rc = run_command(dir, hipcc_cmd(src, hsaco), &log);
  std::cout << "[hipcc --genco gfx1101] rc=" << compile_rc << "\n" << log;
  ASSERT_EQ(compile_rc, 0) << "hipcc gfx1101 genco failed for " << src;

  int grid = 1;
  if (std::string(lc.family) == "bias_gelu") {
    const std::int64_t per_block =
        static_cast<std::int64_t>(lc.block) * lc.vec;
    grid = static_cast<int>((lc.rows * lc.cols + per_block - 1) / per_block);
  } else if (std::string(lc.family) == "reduction") {
    grid = static_cast<int>(lc.cols / lc.vec);
  } else {  // softmax / layernorm: one block per row
    grid = static_cast<int>(lc.rows);
  }

  std::ostringstream gate;
  gate << kPython << " " << kRunHipGate << " --root " << kRepoRoot
       << " --workdir " << dir << "/gate"
       << " --hsaco " << hsaco << " --runner " << kRunner
       << " --symbol " << symbol << " --family " << lc.family
       << " --shape " << lc.rows << "," << lc.cols
       << " --grid " << grid << " --block " << lc.block;

  const int gate_rc = run_command(dir, gate.str(), &log);
  std::cout << "[live gate " << lc.family << " " << lc.rows << "x" << lc.cols
            << " " << lc.tag << "] rc=" << gate_rc << "\n" << log;
  ASSERT_EQ(gate_rc, 0) << "live golden gate failed (verdict not pass:true)";
}

