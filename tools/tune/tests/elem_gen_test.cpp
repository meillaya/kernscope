// --- QA negative: two-pass softmax vec=4 on a non-divisible shape ----------
TEST(ElemGen, SoftmaxNonDivisibleRejectedPreCompile) {
  // cols = 510 is not divisible by block*vec = 256*4 = 1024 (nor by 4): the
  // one-block-per-row kernel is unguarded by design, so the config MUST be
  // rejected pre-compile with a reason naming the divisibility.
  SoftmaxConfig cfg;
  cfg.block = 256;
  cfg.vec_width = 4;
  cfg.mode = ElemMode::kTwoPass;
  const ElemProblem prob = problem(32, 510, "gfx1101");

  const ConfigVerdict verdict = validate_config(cfg, prob);
  ASSERT_FALSE(verdict.valid) << "non-divisible softmax must be rejected";
  EXPECT_NE(verdict.reason.find("not divisible by block*vec_width"),
            std::string::npos)
      << "reason must name the divisibility rule: " << verdict.reason;

  std::string err;
  EXPECT_TRUE(generate_source(cfg, prob, &err).empty())
      << "generator must refuse to emit a non-divisible kernel";
  EXPECT_NE(err.find("invalid softmax config"), std::string::npos) << err;

  // Sanity: the same config on a divisible shape is valid.
  ElemProblem ok_prob = prob;
  ok_prob.cols = 1024;
  EXPECT_TRUE(validate_config(cfg, ok_prob).valid);
}

// --- reduction: invalid mode (onepass) is rejected --------------------------
TEST(ElemGen, ReductionInvalidModeRejected) {
  ReductionConfig cfg;
  cfg.block = 256;
  cfg.vec_width = 2;
  cfg.mode = ElemMode::kOnePass;  // reduction only accepts strided | tree
  const ElemProblem prob = problem(128, 512, "gfx1101");
  const ConfigVerdict verdict = validate_config(cfg, prob);
  EXPECT_FALSE(verdict.valid);
  EXPECT_NE(verdict.reason.find("mode must be strided"), std::string::npos)
      << verdict.reason;
}

// --- full search-space validity over canonical shapes -----------------------
TEST(ElemGen, SearchSpaceAllCombosValid) {
  const ElemProblem bg = problem(64, 512, "gfx1101");
  const ElemProblem row_family = problem(4, 4096, "gfx1101");
  const ElemProblem rd = problem(64, 1024, "gfx1101");
  int total = 0;
  for (const int b : kElemBlockChoices) {
    for (const int v : kElemVecWidthChoices) {
      ++total;
      BiasGeluConfig bg_cfg;
      bg_cfg.block = b;
      bg_cfg.vec_width = v;
      EXPECT_TRUE(validate_config(bg_cfg, bg).valid) << "bias_gelu b=" << b
                                                     << " v=" << v;

      SoftmaxConfig sm_cfg;
      sm_cfg.block = b;
      sm_cfg.vec_width = v;
      for (const ElemMode m : {ElemMode::kOnePass, ElemMode::kTwoPass}) {
        sm_cfg.mode = m;
        ++total;
        EXPECT_TRUE(validate_config(sm_cfg, row_family).valid)
            << "softmax b=" << b << " v=" << v << " mode=" << elem_mode_name(m);
      }

      LayerNormConfig ln_cfg;
      ln_cfg.block = b;
      ln_cfg.vec_width = v;
      for (const ElemMode m : {ElemMode::kOnePass, ElemMode::kTwoPass}) {
        ln_cfg.mode = m;
        ++total;
        EXPECT_TRUE(validate_config(ln_cfg, row_family).valid)
            << "layernorm b=" << b << " v=" << v
            << " mode=" << elem_mode_name(m);
      }

      ReductionConfig rd_cfg;
      rd_cfg.block = b;
      rd_cfg.vec_width = v;
      for (const ElemMode m : {ElemMode::kStrided, ElemMode::kTree}) {
        rd_cfg.mode = m;
        ++total;
        EXPECT_TRUE(validate_config(rd_cfg, rd).valid)
            << "reduction b=" << b << " v=" << v << " mode=" << elem_mode_name(m);
      }
    }
  }
  // 12 bias_gelu + 24 softmax + 24 layernorm + 24 reduction combos.
  EXPECT_EQ(total, 84);
}

// --- invalid search-space membership is rejected ----------------------------
TEST(ElemGen, InvalidSearchSpaceRejected) {
  const ElemProblem prob = problem(64, 512, "gfx1101");
  BiasGeluConfig cfg;
  cfg.block = 64;  // outside {128,256,512,1024}
  cfg.vec_width = 2;
  const ConfigVerdict v = validate_config(cfg, prob);
  EXPECT_FALSE(v.valid);
  EXPECT_NE(v.reason.find("block must be 128, 256, 512 or 1024"),
            std::string::npos) << v.reason;
}

// --- unknown arch is rejected -----------------------------------------------
TEST(ElemGen, UnknownArchRejected) {
  BiasGeluConfig cfg;
  cfg.block = 256;
  cfg.vec_width = 2;
  const ElemProblem prob = problem(64, 512, "sm_99");  // not in the DB
  const ConfigVerdict v = validate_config(cfg, prob);
  EXPECT_FALSE(v.valid);
  EXPECT_NE(v.reason.find("unknown arch"), std::string::npos) << v.reason;
}

