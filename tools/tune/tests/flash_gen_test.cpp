// --- smem over-budget rejection (pre-compile, with the reason) --------------
TEST(FlashGen, OverBudgetRejectedPreCompile) {
  // Br=64, Bc=64, d=64, stages=1, padding on gfx1101 needs 67072 bytes >
  // the 64 KB per-block LDS budget -> MUST be rejected before any compile.
  FlashAttentionConfig cfg;
  cfg.tile_m = 64;
  cfg.tile_n = 64;
  cfg.stages = 1;
  cfg.vec_width = 1;
  cfg.smem_layout = SmemLayout::kPadding;

  FlashAttentionProblem prob;
  prob.nq = 64;
  prob.nk = 64;
  prob.d = 64;
  prob.arch = "gfx1101";

  const ConfigVerdict verdict = validate_config(cfg, prob);
  ASSERT_FALSE(verdict.valid) << "over-budget config must be rejected";
  EXPECT_NE(verdict.reason.find("smem budget"), std::string::npos)
      << "reason must name the budget: " << verdict.reason;
  EXPECT_NE(verdict.reason.find("gfx1101"), std::string::npos) << verdict.reason;

  std::string err;
  EXPECT_TRUE(generate_source(cfg, prob, &err).empty())
      << "generator must refuse to emit an over-budget kernel";
  EXPECT_NE(err.find("invalid FlashAttention config"), std::string::npos) << err;

  // Sanity: the SAME config fits sm_80's 163 KB budget -> valid there.
  FlashAttentionProblem sm80 = prob;
  sm80.arch = "sm_80";
  EXPECT_TRUE(validate_config(cfg, sm80).valid)
      << "same tiles fit sm_80's larger budget";
}

// --- roofline AI cross-check (4N^2d formula) --------------------------------
TEST(FlashGen, RooflineAiMatches4N2d) {
  constexpr std::int64_t n = 64;
  constexpr std::int64_t d = 32;
  EXPECT_EQ(flash_attention_flops(n, d), 4 * n * n * d);

  kernscope::roofline::Shape shape;
  shape.n = n;
  shape.d = d;
  shape.dtype_bytes = 2;
  using kernscope::roofline::KernelFamily;
  const std::int64_t lib_flops =
      kernscope::roofline::compute_flops(KernelFamily::kFlashAttention, shape);
  EXPECT_EQ(flash_attention_flops(n, d), lib_flops)
      << "generator FLOPs model must equal libs/roofline 4N^2d";

  const std::int64_t lib_bytes =
      kernscope::roofline::compute_bytes_moved(KernelFamily::kFlashAttention,
                                               shape);
  const double lib_ai = kernscope::roofline::arithmetic_intensity(
      KernelFamily::kFlashAttention, shape);
  // Generator's AI entry uses the same standard-attention traffic model
  // s*(4Nd + 4N^2) with s = dtype_bytes = 2.
  const std::int64_t gen_bytes = 2 * (4 * n * d + 4 * n * n);
  EXPECT_EQ(lib_bytes, gen_bytes);
  EXPECT_NEAR(static_cast<double>(flash_attention_flops(n, d)) /
                  static_cast<double>(gen_bytes),
              lib_ai, 1e-9);
  std::cout << "roofline AI(N=64,d=32) = " << lib_ai << " FLOP/byte\n";
}

// --- full search-space validity over the run shape --------------------------
TEST(FlashGen, SearchSpaceAllCombosValidForRunShape) {
  const FlashAttentionProblem prob = run_problem();
  int valid = 0;
  int rejected = 0;
  int total = 0;
  for (const int br : kTileChoices)
    for (const int bc : kTileChoices)
      for (const int st : kStageChoices)
        for (const int v : kVecWidthChoices)
          for (const SmemLayout lay : kSmemLayoutChoices) {
            FlashAttentionConfig cfg;
            cfg.tile_m = br;
            cfg.tile_n = bc;
            cfg.stages = st;
            cfg.vec_width = v;
            cfg.smem_layout = lay;
            const ConfigVerdict vd = validate_config(cfg, prob);
            ++total;
            if (!vd.valid) {
              ++rejected;
              ADD_FAILURE() << "unexpected rejection: Br=" << br << " Bc=" << bc
                            << " st=" << st << " v=" << v << " lay="
                            << smem_layout_name(lay) << " : " << vd.reason;
              continue;
            }
            ++valid;
            std::string err;
            EXPECT_FALSE(generate_source(cfg, prob, &err).empty()) << err;
          }
  EXPECT_EQ(total, 48);
  EXPECT_EQ(valid, 48) << "every search-space combo must be valid for "
                          "N=64, d=32 (fits the 64 KB gfx1101 budget)";
  EXPECT_EQ(rejected, 0);
}

// --- invalid search-space membership is rejected ----------------------------
TEST(FlashGen, InvalidSearchSpaceRejected) {
  const FlashAttentionProblem prob = run_problem();
  FlashAttentionConfig cfg = live_config(false);
  cfg.tile_m = 16;  // outside {32, 64}
  const ConfigVerdict v = validate_config(cfg, prob);
  EXPECT_FALSE(v.valid);
  EXPECT_NE(v.reason.find("tile_m"), std::string::npos) << v.reason;
}

