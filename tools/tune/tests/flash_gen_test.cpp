// The canonical live-run shape (todo 27 acceptance: N=64, d=32, heads
// flattened): Nq == Nk == 64, head dim 32, validated against the golden
// attention reference on gfx1101.
FlashAttentionProblem run_problem() {
  FlashAttentionProblem prob;
  prob.nq = 64;
  prob.nk = 64;
  prob.d = 32;
  prob.arch = "gfx1101";
  prob.dtype_bytes = 2;
  return prob;
}

// The default live config: Br=32, Bc=32, stages=1, vec=1, padding (validated
