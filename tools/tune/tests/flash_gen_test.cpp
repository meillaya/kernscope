// --- gpu-amd: live golden gates on gfx1101 ---------------------------------

void run_live_gate(const FlashAttentionConfig &cfg, const char *tag) {
  ASSERT_FALSE(kHipcc.empty()) << "hipcc not found at configure time";
  ASSERT_FALSE(kRunner.empty()) << "kernscope_templates_hip_runner target "
                                   "missing (kernels/templates)";
  const FlashAttentionProblem prob = run_problem();
  const std::string dir = make_workdir(tag);
  const std::string src = emit_kernel(cfg, prob, dir);
  ASSERT_FALSE(src.empty());

  const std::string hsaco = dir + "/flash_attn.hsaco";
  std::string log;
  const int compile_rc = run_command(dir, hipcc_cmd(src, hsaco), &log);
  std::cout << "[hipcc --genco gfx1101] rc=" << compile_rc << "\n" << log;
  ASSERT_EQ(compile_rc, 0) << "hipcc gfx1101 genco failed for " << src;

  const LaunchGeometry geo = launch_geometry(cfg, prob);
  const std::string grid = std::to_string(geo.grid_x) +
                           (geo.grid_y > 1 ? "x" + std::to_string(geo.grid_y) : "");
  const std::string block = std::to_string(geo.block_x) + "x" +
                            std::to_string(geo.block_y);

  std::ostringstream gate;
  gate << kPython << " " << kRunHipGate << " --root " << kRepoRoot
       << " --workdir " << dir << "/gate"
       << " --hsaco " << hsaco << " --runner " << kRunner
       << " --symbol " << kernel_symbol(cfg)
       << " --family attention --shape 64,64,32"
       << " --grid " << grid << " --block " << block;
  if (cfg.causal)
    gate << " --causal";

  const int gate_rc = run_command(dir, gate.str(), &log);
  std::cout << "[live gate] rc=" << gate_rc << "\n" << log;
  ASSERT_EQ(gate_rc, 0) << "live golden gate failed (verdict not pass:true)";
}

TEST(FlashGenLive, AttentionGoldenPass) {
  run_live_gate(live_config(false), "nc");
}

TEST(FlashGenLive, AttentionCausalGoldenPass) {
  run_live_gate(live_config(true), "causal");
}

