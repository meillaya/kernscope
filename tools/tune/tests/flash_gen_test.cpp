// --- nvcc sm_80/sm_90 compile-only gates ------------------------------------
TEST(FlashGen, NvccCompileGate) {
  if (kNvcc.empty())
    GTEST_SKIP() << "nvcc not found at configure time (tools/tune CMakeLists)";
  const FlashAttentionProblem prob = run_problem();
  for (const FlashAttentionConfig &cfg : kCompileVariants) {
    const std::string dir = make_workdir("nvcc");
    const std::string src = emit_kernel(cfg, prob, dir);
    ASSERT_FALSE(src.empty());
    for (const char *arch : {"sm_80", "sm_90"}) {
      const std::string obj = dir + "/" + kernel_symbol(cfg) + "_" + arch + ".o";
      std::string log;
      const int rc = run_command(dir, nvcc_cmd(src, obj, arch), &log);
      std::cout << "[nvcc " << arch << "] " << kernel_symbol(cfg)
                << " rc=" << rc << "\n" << log;
      EXPECT_EQ(rc, 0) << "nvcc " << arch << " compile gate failed";
    }
  }
}

