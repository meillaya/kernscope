TEST(MatmulGen, VecMisdivisionRejectedPreCompile) {
  // BN=64, warps=1 -> per-thread column fragment cpt = 2; vec_width=4 does not
  // divide it -> rejected before any compile.
  MatmulConfig cfg = live_config();
  cfg.warps = 1;
  cfg.vec_width = 4;

  const ConfigVerdict verdict = validate_config(cfg, run_problem());
  ASSERT_FALSE(verdict.valid) << "misdivisible vector width must be rejected";
  EXPECT_NE(verdict.reason.find("vector width"), std::string::npos)
      << "reason must name the vector-width rule: " << verdict.reason;
  EXPECT_NE(verdict.reason.find("cpt"), std::string::npos) << verdict.reason;
}

// --- full search-space enumeration sanity -----------------------------------
// Every (BM,BN,BK,warps,stages,layout,vec,unroll) combo is enumerated
// deterministically; rejected combos carry a non-empty reason (the pre-screen
// NEVER produces an "invalid without explanation" verdict).
TEST(MatmulGen, SearchSpaceEnumerationSanity) {
  const MatmulProblem prob = run_problem();
  std::int64_t total = 0;
  int rejected_no_reason = 0;
  int emitted_invalid = 0;
  for (const int bm : kTileMChoices)
    for (const int bn : kTileNChoices)
      for (const int bk : kTileKChoices)
        for (const int warps : kWarpChoices)
          for (const int st : kStageChoices)
            for (const SmemLayout lay : kSmemLayoutChoices)
              for (const int v : kVecWidthChoices)
                for (const int u : kUnrollChoices) {
                  MatmulConfig cfg;
                  cfg.tile_m = bm;
                  cfg.tile_n = bn;
                  cfg.tile_k = bk;
                  cfg.warps = warps;
                  cfg.stages = st;
                  cfg.vec_width = v;
                  cfg.smem_layout = lay;
                  cfg.unroll = u;
                  ++total;
                  const ConfigVerdict vd = validate_config(cfg, prob);
                  if (!vd.valid) {
                    if (vd.reason.empty())
                      ++rejected_no_reason;
                    continue;
                  }
                  std::string err;
                  if (generate_source(cfg, prob, &err).empty()) {
                    ++emitted_invalid;
                    ADD_FAILURE() << "valid config refused to emit: " << err;
                  }
                }
  EXPECT_EQ(total, 4608) << "2·2·4·4·4·2·3·3 search-space size";
  EXPECT_EQ(rejected_no_reason, 0)
      << "every rejected config must carry an explanation";
  EXPECT_EQ(emitted_invalid, 0);
}

