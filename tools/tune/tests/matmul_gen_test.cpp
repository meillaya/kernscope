// --- bounded-grid enumeration count (exactly 16) ----------------------------
TEST(MatmulGen, GridEnumerationCountExact) {
  const MatmulProblem prob = run_problem();
  // 2 BMxBN pairs x 2 BK x 2 warps x 2 stages = 16 configs (task contract);
  // vec=1, padding, unroll=1 fixed. Every combo is enumerated deterministically
  // (some are then rejected pre-compile by the register budget — that is the
  // point of the pre-screen, not a failure).
  const std::array<std::pair<int, int>, 2> tile_pairs{
      std::pair<int, int>{64, 64}, std::pair<int, int>{128, 128}};
  int total = 0;
  int valid = 0;
  int rejected = 0;
  for (const auto &[bm, bn] : tile_pairs)
    for (const int bk : {16, 32})
      for (const int warps : {1, 4})
        for (const int stages : {1, 2}) {
          MatmulConfig cfg;
          cfg.tile_m = bm;
          cfg.tile_n = bn;
          cfg.tile_k = bk;
          cfg.warps = warps;
          cfg.stages = stages;
          cfg.vec_width = 1;
          cfg.smem_layout = SmemLayout::kPadding;
          cfg.unroll = 1;
          ++total;
          const ConfigVerdict vd = validate_config(cfg, prob);
          if (!vd.valid) {
            ++rejected;
            continue;
          }
          ++valid;
          std::string err;
          EXPECT_FALSE(generate_source(cfg, prob, &err).empty())
              << "valid config must emit source: " << err;
        }
  EXPECT_EQ(total, 16) << "bounded grid must enumerate exactly 16 configs";
  EXPECT_EQ(valid + rejected, 16);
  EXPECT_GT(valid, 0) << "at least one grid combo must be feasible (128x128 "
                         "at warps=4, BK=16, stages=1/2)";
  EXPECT_EQ(rejected, 16 - valid);
  std::cout << "grid: total=16 valid=" << valid << " rejected=" << rejected
            << "\n";
}

// --- invalid-config rejection (count exact, reason asserted) ----------------
// Four deliberately-invalid configs; every one must be rejected PRE-COMPILE
// with a non-empty reason, and generate_source must refuse to emit.
TEST(MatmulGen, RejectionCountExact) {
  const MatmulProblem prob = run_problem();

  // 1. smem over-budget on gfx1101: BM=BN=128, BK=64, stages=2, padding needs
  //    132608 bytes > the 64 KB LDS budget -> rejected with the budget named.
  MatmulConfig smem_bad;
  smem_bad.tile_m = 128;
  smem_bad.tile_n = 128;
  smem_bad.tile_k = 64;
  smem_bad.warps = 4;
  smem_bad.stages = 2;
  smem_bad.vec_width = 1;
  smem_bad.smem_layout = SmemLayout::kPadding;
  smem_bad.unroll = 1;

  // 2. register over-budget: BM=BN=128 at warps=1 -> 512 acc fragment regs
  //    + 32 overhead > 255 max_regs_per_thread.
  MatmulConfig reg_bad = smem_bad;
  reg_bad.tile_k = 16;
  reg_bad.stages = 1;
  reg_bad.warps = 1;

  // 3. vector-width misdivision: BN=64, warps=1 -> cpt = 2, vec=4 does not
  //    divide the per-thread column fragment.
  MatmulConfig vec_bad;
  vec_bad.tile_m = 64;
  vec_bad.tile_n = 64;
  vec_bad.tile_k = 16;
  vec_bad.warps = 1;
  vec_bad.stages = 1;
  vec_bad.vec_width = 4;
  vec_bad.smem_layout = SmemLayout::kPadding;
  vec_bad.unroll = 1;

  // 4. outside the search space: BK=48.
  MatmulConfig space_bad = live_config();
  space_bad.tile_k = 48;

  const MatmulConfig *invalid[] = {&smem_bad, &reg_bad, &vec_bad, &space_bad};
  int rejected = 0;
  for (const MatmulConfig *cfg : invalid) {
    const ConfigVerdict vd = validate_config(*cfg, prob);
    EXPECT_FALSE(vd.valid) << "config must be rejected pre-compile";
    if (!vd.valid) {
      ++rejected;
      EXPECT_FALSE(vd.reason.empty());
      std::string err;
      EXPECT_TRUE(generate_source(*cfg, prob, &err).empty())
          << "generator must refuse to emit an invalid kernel";
      EXPECT_NE(err.find("invalid matmul config"), std::string::npos) << err;
    }
  }
  EXPECT_EQ(rejected, 4) << "all four deliberately-invalid configs rejected";
}

// --- rejection reasons name the budget / constraint (asserted) --------------
TEST(MatmulGen, OverBudgetRejectedPreCompile) {
  // Same config as RejectionCountExact case 1: over-budget on gfx1101.
  MatmulConfig cfg;
  cfg.tile_m = 128;
  cfg.tile_n = 128;
  cfg.tile_k = 64;
  cfg.warps = 4;
  cfg.stages = 2;
  cfg.vec_width = 1;
  cfg.smem_layout = SmemLayout::kPadding;
  cfg.unroll = 1;

  const ConfigVerdict verdict = validate_config(cfg, run_problem());
  ASSERT_FALSE(verdict.valid) << "over-budget config must be rejected";
  EXPECT_NE(verdict.reason.find("smem budget"), std::string::npos)
      << "reason must name the budget: " << verdict.reason;
  EXPECT_NE(verdict.reason.find("132608"), std::string::npos) << verdict.reason;
  EXPECT_NE(verdict.reason.find("gfx1101"), std::string::npos) << verdict.reason;

  std::string err;
  EXPECT_TRUE(generate_source(cfg, run_problem(), &err).empty())
      << "generator must refuse to emit an over-budget kernel";
  EXPECT_NE(err.find("invalid matmul config"), std::string::npos) << err;

  // Sanity: the SAME config fits sm_80's 163 KB budget -> valid there.
  MatmulProblem sm80 = run_problem();
  sm80.arch = "sm_80";
  EXPECT_TRUE(validate_config(cfg, sm80).valid)
      << "same tiles fit sm_80's larger budget";
}

