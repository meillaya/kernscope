//===- layernorm_gen.cpp - layer-norm template generator ------------------===//
//
// Implementation of kernscope::tune::layernorm_gen (todo 26). Emits a
// single-source portable .hip kernel for normalization over the last axis
// (one block per row, row length == block*vec_width) and validates every
// candidate PRE-COMPILE (search-space membership, arch existence, block
// limit, cols % (block*vec_width) divisibility, smem-staged row within the
// arch's per-block budget) with a reason string.
//
// The generated kernel matches the golden reference (refs.layernorm): biased
// population variance, eps pinned to 1e-5, fp32 arithmetic, bf16 out. The
// `mode` dimension selects: kOnePass = single register walk computing sum +
// sum of squares with warp-shuffle reductions (mean = s1/n, var = s2/n -
// mean^2); kTwoPass = the classic two-pass formula (pass 1: smem tree sum ->
// mean; pass 2: smem tree over the squared deviations -> var), the formula
// the golden reference describes.
//
//===----------------------------------------------------------------------===//

#include "kernscope/tune/layernorm_gen.h"

#include <sstream>

namespace kernscope::tune {

ConfigVerdict validate_config(const LayerNormConfig &cfg,
                              const ElemProblem &prob) noexcept {
  if (cfg.mode != ElemMode::kOnePass && cfg.mode != ElemMode::kTwoPass)
    return {false, "layernorm: mode must be onepass (single-walk sum/sumsq) "
                   "or twopass (mean then variance)"};
  ConfigVerdict v = detail::elem_common_validate(
      "layernorm", cfg.block, cfg.vec_width, prob.arch, prob.rows, prob.cols);
  if (!v.valid)
    return v;
  const std::int64_t row =
      static_cast<std::int64_t>(cfg.block) * cfg.vec_width;
  if (prob.cols % row != 0)
    return {false, "layernorm: cols (" + std::to_string(prob.cols) +
                       ") not divisible by block*vec_width (" +
                       std::to_string(row) +
                       "): one block per row, unguarded by design"};
  // The twopass kernel stages the fp32 row in shared memory; check the
  // budget via libs/arch like the flash generator does for its tiles.
  const std::int64_t row_bytes = 4 * row;
  const ArchInfo *a = nullptr;
  try {
    a = &get_arch(prob.arch);
  } catch (const std::out_of_range &) {
    return {false, "unknown arch '" + prob.arch + "' (libs/arch DB)"};
  }
  if (a->smem_per_block_max_bytes > 0 &&
      row_bytes > a->smem_per_block_max_bytes)
    return {false, "layernorm: smem-staged row needs " +
                       std::to_string(row_bytes) + " bytes > " +
                       std::to_string(a->smem_per_block_max_bytes) +
                       " available per block on " + std::string(a->name)};
  return {true, ""};
}

LaunchGeometry launch_geometry(const LayerNormConfig &cfg,
                               const ElemProblem &prob) noexcept {
  LaunchGeometry g;
  g.grid_x = static_cast<int>(prob.rows);
  g.block_x = cfg.block;
  return g;
}

std::string kernel_symbol(const LayerNormConfig &cfg) {
  std::string sym = "kernscope_tune_layernorm_b";
  sym += std::to_string(cfg.block);
  sym += "_v" + std::to_string(cfg.vec_width);
  sym += std::string("_") + elem_mode_name(cfg.mode);
  return sym;
}

std::string generate_source(const LayerNormConfig &cfg,
                            const ElemProblem &prob, std::string *error) {
  const ConfigVerdict verdict = validate_config(cfg, prob);
  if (!verdict.valid) {
    if (error)
      *error = "invalid layernorm config: " + verdict.reason;
    return "";
  }

  const std::string symbol = kernel_symbol(cfg);
  const bool onepass = (cfg.mode == ElemMode::kOnePass);
  const int row_elems = cfg.block * cfg.vec_width;

  std::ostringstream out;
  out << "//===- " << symbol
      << ".hip - layer-norm template (GENERATED) -===//\n"
         "//\n"
         "// GENERATED by kernscope::tune layernorm generator (todo 26) — do "
         "not edit.\n"
         "// Config: block="
      << cfg.block << " vec_width=" << cfg.vec_width << " mode="
      << elem_mode_name(cfg.mode) << ".\n"
         "//\n"
         "// y[r,c] = (x[r,c] - mean_r) / sqrt(var_r + eps) * gamma[c] + "
         "beta[c]\n"
         "// over the last axis, matching tests/golden refs.layernorm (biased\n"
         "// population variance, eps = 1e-5 pinned). bf16 in, fp32 "
         "mean/variance,\n"
         "// bf16 out. One block per row; row length == block*vec_width "
         "(unguarded\n"
         "// by design). Variance algorithm: "
      << (onepass ? "one-pass sum/sum-of-squares (warp-shuffle reductions)"
                  : "two-pass (shared-memory tree; sum -> mean, then "
                    "squared deviations -> var)")
      << ".\n"
         "// Single-source portable convention (kernels/templates, todo 24):\n"
         "// nvcc -x cu (sm_80/sm_90) AND hipcc (gfx1101).\n"
         "//\n"
         "//===----------------------------------------------------------------------===//\n"
         "\n"
         "#include \"kernscope/kernel_traits.h\"\n"
         "\n"
         "namespace {\n"
         "constexpr int kVec = "
      << cfg.vec_width << ";          // elements per thread\n"
         "constexpr int kRow = "
      << row_elems << ";    // block * kVec (row length)\n"
         "constexpr float kEps = 1e-5f;  // pinned by refs.layernorm\n"
         "// Portable warp-shuffle (HIP 2-arg vs CUDA _sync forms).\n"
         "#if defined(__HIP_PLATFORM_AMD__)\n"
         "#define KERNSCOPE_SHFL_XOR(v, off) __shfl_xor((v), (off))\n"
         "#else\n"
         "#define KERNSCOPE_SHFL_XOR(v, off) \\\n"
         "  __shfl_xor_sync(0xffffffffu, (v), (off))\n"
         "#endif\n"
         "\n"
         "__shared__ float ks_sred[1024];  // reduce buffer (>= max block "
         "size)\n";

  if (!onepass) {
    out << "__shared__ float ks_row[kRow];   // fp32-staged row for the "
           "second pass\n";
  }

  out << "\n"
         "// Block-wide sum visible to every thread.\n"
         "inline __device__ float ks_block_sum(float v) {\n"
         "  __syncthreads();  // order against the previous reduce helper's final read\n";

  if (onepass) {
    out << "  const int warp = threadIdx.x >> 5;\n"
           "  const int lane = threadIdx.x & 31;\n"
           "  for (int off = 16; off >= 1; off >>= 1)\n"
           "    v += KERNSCOPE_SHFL_XOR(v, off);\n"
           "  if (lane == 0) ks_sred[warp] = v;\n"
           "  __syncthreads();\n"
           "  float r = 0.0f;\n"
           "  if (warp == 0) {\n"
           "    const int nw = (blockDim.x + 31) >> 5;\n"
           "    r = (lane < nw) ? ks_sred[lane] : 0.0f;\n"
           "    for (int off = 16; off >= 1; off >>= 1)\n"
           "      r += KERNSCOPE_SHFL_XOR(r, off);\n"
           "    if (lane == 0) ks_sred[0] = r;\n"
           "  }\n";
  } else {
    out << "  ks_sred[threadIdx.x] = v;\n"
           "  __syncthreads();\n"
           "  for (int off = blockDim.x >> 1; off > 0; off >>= 1) {\n"
           "    if (threadIdx.x < off)\n"
           "      ks_sred[threadIdx.x] += ks_sred[threadIdx.x + off];\n"
           "    __syncthreads();\n"
           "  }\n";
  }

  out << "  __syncthreads();\n"
         "  return ks_sred[0];\n"
         "}\n"
         "} // namespace\n"
         "\n"
         "extern \"C\" __global__ void "
      << symbol
      << "(const ks_bf16 *x, const ks_bf16 *gamma, const ks_bf16 *beta,\n"
         "                             ks_bf16 *out, int rows, int cols) {\n"
         "  const int r = blockIdx.x;\n"
         "  if (r >= rows) return;\n"
         "  const int tid = threadIdx.x;\n";

  if (onepass) {
    out << "  // One walk over the row (register-resident): sum and sum of\n"
           "  // squares in fp32, combined with warp-shuffle reductions.\n"
           "  float v[kVec];\n"
           "  float s1 = 0.0f, s2 = 0.0f;\n"
           "  #pragma unroll\n"
           "  for (int vv = 0; vv < kVec; ++vv) {\n"
           "    v[vv] = ks_bf16_to_float(x[r * cols + tid * kVec + vv]);\n"
           "    s1 += v[vv];\n"
           "    s2 += v[vv] * v[vv];\n"
           "  }\n"
           "  const float inv_n = 1.0f / static_cast<float>(cols);\n"
           "  const float mean = ks_block_sum(s1) * inv_n;\n"
           "  const float var = ks_block_sum(s2) * inv_n - mean * mean;\n"
           "  const float inv_std = 1.0f / sqrtf(var + kEps);\n"
           "  #pragma unroll\n"
           "  for (int vv = 0; vv < kVec; ++vv) {\n"
           "    const int c = tid * kVec + vv;\n"
           "    const float g = ks_bf16_to_float(gamma[c]);\n"
           "    const float b = ks_bf16_to_float(beta[c]);\n"
           "    out[r * cols + c] = ks_float_to_bf16(\n"
           "        (v[vv] - mean) * inv_std * g + b);\n"
           "  }\n";
  } else {
    out << "  // Two-pass: stage the fp32 row in smem, tree-reduce the sum to\n"
           "  // the mean, then tree-reduce the squared deviations to the\n"
           "  // (biased) population variance — the formula the golden\n"
           "  // reference describes (refs.layernorm L97-98).\n"
           "  float v[kVec];\n"
           "  float s1 = 0.0f;\n"
           "  #pragma unroll\n"
           "  for (int vv = 0; vv < kVec; ++vv) {\n"
           "    v[vv] = ks_bf16_to_float(x[r * cols + tid * kVec + vv]);\n"
           "    ks_row[tid * kVec + vv] = v[vv];\n"
           "    s1 += v[vv];\n"
           "  }\n"
           "  const float inv_n = 1.0f / static_cast<float>(cols);\n"
           "  const float mean = ks_block_sum(s1) * inv_n;\n"
           "  float s2 = 0.0f;\n"
           "  #pragma unroll\n"
           "  for (int vv = 0; vv < kVec; ++vv) {\n"
           "    const float d = ks_row[tid * kVec + vv] - mean;\n"
           "    s2 += d * d;\n"
           "  }\n"
           "  const float var = ks_block_sum(s2) * inv_n;\n"
           "  const float inv_std = 1.0f / sqrtf(var + kEps);\n"
           "  #pragma unroll\n"
           "  for (int vv = 0; vv < kVec; ++vv) {\n"
           "    const int c = tid * kVec + vv;\n"
           "    const float g = ks_bf16_to_float(gamma[c]);\n"
           "    const float b = ks_bf16_to_float(beta[c]);\n"
           "    out[r * cols + c] = ks_float_to_bf16(\n"
           "        (ks_row[tid * kVec + vv] - mean) * inv_std * g + b);\n"
           "  }\n";
  }

  out << "}\n";

  return out.str();
}

bool generate_to_file(const LayerNormConfig &cfg, const ElemProblem &prob,
                      const std::string &path, std::string *error) {
  const std::string src = generate_source(cfg, prob, error);
  if (src.empty())
    return false;
  return detail::elem_write_file(path, src, error);
}

} // namespace kernscope::tune
