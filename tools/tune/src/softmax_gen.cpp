//===- softmax_gen.cpp - softmax template generator -----------------------===//
//
// Implementation of kernscope::tune::softmax_gen (todo 26). Emits a
// single-source portable .hip kernel for the numerically stable row softmax
// (one block per row, row length == block*vec_width) and validates every
// candidate PRE-COMPILE (search-space membership, arch existence, block
// limit, cols % (block*vec_width) divisibility) with a reason string.
//
// The generated kernel matches the golden reference (refs.softmax): fp32
// row max, shifted exp, row sum, divide; bf16 out. The `mode` dimension
// selects the block reduction strategy: kOnePass = warp-shuffle
// (register-resident __shfl_xor tree + one cross-warp smem combine),
// kTwoPass = shared-memory partial tree.
//
//===----------------------------------------------------------------------===//

#include "kernscope/tune/softmax_gen.h"

#include <sstream>

namespace kernscope::tune {

ConfigVerdict validate_config(const SoftmaxConfig &cfg,
                              const ElemProblem &prob) noexcept {
  if (cfg.mode != ElemMode::kOnePass && cfg.mode != ElemMode::kTwoPass)
    return {false, "softmax: mode must be onepass (warp-shuffle) or twopass "
                   "(shared-memory partial)"};
  ConfigVerdict v = detail::elem_common_validate(
      "softmax", cfg.block, cfg.vec_width, prob.arch, prob.rows, prob.cols);
  if (!v.valid)
    return v;
  const std::int64_t row =
      static_cast<std::int64_t>(cfg.block) * cfg.vec_width;
  if (prob.cols % row != 0)
    return {false, "softmax: cols (" + std::to_string(prob.cols) +
                       ") not divisible by block*vec_width (" +
                       std::to_string(row) +
                       "): one block per row, unguarded by design"};
  return {true, ""};
}

LaunchGeometry launch_geometry(const SoftmaxConfig &cfg,
                               const ElemProblem &prob) noexcept {
  LaunchGeometry g;
  g.grid_x = static_cast<int>(prob.rows);
  g.block_x = cfg.block;
  return g;
}

std::string kernel_symbol(const SoftmaxConfig &cfg) {
  std::string sym = "kernscope_tune_softmax_b";
  sym += std::to_string(cfg.block);
  sym += "_v" + std::to_string(cfg.vec_width);
  sym += std::string("_") + elem_mode_name(cfg.mode);
  return sym;
}

std::string generate_source(const SoftmaxConfig &cfg,
                            const ElemProblem &prob, std::string *error) {
  const ConfigVerdict verdict = validate_config(cfg, prob);
  if (!verdict.valid) {
    if (error)
      *error = "invalid softmax config: " + verdict.reason;
    return "";
  }

  const std::string symbol = kernel_symbol(cfg);
  const bool shuffle = (cfg.mode == ElemMode::kOnePass);

  std::ostringstream out;
  out << "//===- " << symbol
      << ".hip - row-softmax template (GENERATED) -===//\n"
         "//\n"
         "// GENERATED by kernscope::tune softmax generator (todo 26) — do "
         "not edit.\n"
         "// Config: block="
      << cfg.block << " vec_width=" << cfg.vec_width << " mode="
      << elem_mode_name(cfg.mode) << ".\n"
         "//\n"
         "// Numerically stable row softmax over the last axis (bf16 in, "
         "fp32\n"
         "// max/exp/sum, bf16 out), matching tests/golden refs.softmax. One "
         "block\n"
         "// per row; row length == block*vec_width (unguarded by design, "
         "like the\n"
         "// flash lite kernel). Reduction strategy: "
      << (shuffle ? "warp-shuffle" : "shared-memory partial") << ".\n"
         "// Single-source portable convention (kernels/templates, todo 24):\n"
         "// nvcc -x cu (sm_80/sm_90) AND hipcc (gfx1101).\n"
         "//\n"
         "//===----------------------------------------------------------------------===//\n"
         "\n"
         "#include \"kernscope/kernel_traits.h\"\n"
         "\n"
         "namespace {\n"
         "constexpr int kVec = "
      << cfg.vec_width << ";          // elements per thread\n"
         "// Portable warp-shuffle (HIP 2-arg vs CUDA _sync forms).\n"
         "#if defined(__HIP_PLATFORM_AMD__)\n"
         "#define KERNSCOPE_SHFL_XOR(v, off) __shfl_xor((v), (off))\n"
         "#else\n"
         "#define KERNSCOPE_SHFL_XOR(v, off) \\\n"
         "  __shfl_xor_sync(0xffffffffu, (v), (off))\n"
         "#endif\n"
         "\n"
         "// Per-warp butterfly + one cross-warp shared-memory combine (mode\n"
         "// onepass) OR a full shared-memory halving tree (mode twopass);\n"
         "// the result is block-wide and visible to every thread.\n"
         "__shared__ float ks_sred[1024];  // >= max block size (1024)\n"
         "\n"
         "inline __device__ float ks_reduce_max(float v) {\n"
         "  __syncthreads();  // order against the previous reduce helper's final read\n";

  if (shuffle) {
    out << "  const int warp = threadIdx.x >> 5;\n"
           "  const int lane = threadIdx.x & 31;\n"
           "  for (int off = 16; off >= 1; off >>= 1)\n"
           "    v = fmaxf(v, KERNSCOPE_SHFL_XOR(v, off));\n"
           "  if (lane == 0) ks_sred[warp] = v;\n"
           "  __syncthreads();\n"
           "  float r = -INFINITY;\n"
           "  if (warp == 0) {\n"
           "    const int nw = (blockDim.x + 31) >> 5;\n"
           "    r = (lane < nw) ? ks_sred[lane] : -INFINITY;\n"
           "    for (int off = 16; off >= 1; off >>= 1)\n"
           "      r = fmaxf(r, KERNSCOPE_SHFL_XOR(r, off));\n"
           "    if (lane == 0) ks_sred[0] = r;\n"
           "  }\n";
  } else {
    out << "  ks_sred[threadIdx.x] = v;\n"
           "  __syncthreads();\n"
           "  for (int off = blockDim.x >> 1; off > 0; off >>= 1) {\n"
           "    if (threadIdx.x < off)\n"
           "      ks_sred[threadIdx.x] = fmaxf(ks_sred[threadIdx.x],\n"
           "                                   ks_sred[threadIdx.x + off]);\n"
           "    __syncthreads();\n"
           "  }\n";
  }

  out << "  __syncthreads();\n"
         "  return ks_sred[0];\n"
         "}\n"
         "\n"
         "inline __device__ float ks_reduce_sum(float v) {\n"
         "  __syncthreads();  // order against the previous reduce helper's final read\n";

  if (shuffle) {
    out << "  const int warp = threadIdx.x >> 5;\n"
           "  const int lane = threadIdx.x & 31;\n"
           "  for (int off = 16; off >= 1; off >>= 1)\n"
           "    v += KERNSCOPE_SHFL_XOR(v, off);\n"
           "  if (lane == 0) ks_sred[warp] = v;\n"
           "  __syncthreads();\n"
           "  float r = 0.0f;\n"
           "  if (warp == 0) {\n"
           "    const int nw = (blockDim.x + 31) >> 5;\n"
           "    r = (lane < nw) ? ks_sred[lane] : 0.0f;\n"
           "    for (int off = 16; off >= 1; off >>= 1)\n"
           "      r += KERNSCOPE_SHFL_XOR(r, off);\n"
           "    if (lane == 0) ks_sred[0] = r;\n"
           "  }\n";
  } else {
    out << "  ks_sred[threadIdx.x] = v;\n"
           "  __syncthreads();\n"
           "  for (int off = blockDim.x >> 1; off > 0; off >>= 1) {\n"
           "    if (threadIdx.x < off)\n"
           "      ks_sred[threadIdx.x] += ks_sred[threadIdx.x + off];\n"
           "    __syncthreads();\n"
           "  }\n";
  }

  out << "  __syncthreads();\n"
         "  return ks_sred[0];\n"
         "}\n"
         "} // namespace\n"
         "\n"
         "extern \"C\" __global__ void "
      << symbol
      << "(const ks_bf16 *x, ks_bf16 *out, int rows, int cols) {\n"
         "  const int r = blockIdx.x;\n"
         "  if (r >= rows) return;\n"
         "  const int tid = threadIdx.x;\n"
         "  // Register-resident row segment (cols == block*kVec, so every\n"
         "  // access is in-bounds by construction).\n"
         "  float v[kVec];\n"
         "  #pragma unroll\n"
         "  for (int vv = 0; vv < kVec; ++vv)\n"
         "    v[vv] = ks_bf16_to_float(x[r * cols + tid * kVec + vv]);\n"
         "  // Stable softmax: shift by the row max, exp, normalize (fp32).\n"
         "  float p = -INFINITY;\n"
         "  #pragma unroll\n"
         "  for (int vv = 0; vv < kVec; ++vv) p = fmaxf(p, v[vv]);\n"
         "  const float m = ks_reduce_max(p);\n"
         "  float e[kVec];\n"
         "  float s = 0.0f;\n"
         "  #pragma unroll\n"
         "  for (int vv = 0; vv < kVec; ++vv) {\n"
         "    e[vv] = expf(v[vv] - m);\n"
         "    s += e[vv];\n"
         "  }\n"
         "  const float sum = ks_reduce_sum(s);\n"
         "  #pragma unroll\n"
         "  for (int vv = 0; vv < kVec; ++vv)\n"
         "    out[r * cols + tid * kVec + vv] =\n"
         "        ks_float_to_bf16(e[vv] / sum);\n"
         "}\n";

  return out.str();
}

bool generate_to_file(const SoftmaxConfig &cfg, const ElemProblem &prob,
                      const std::string &path, std::string *error) {
  const std::string src = generate_source(cfg, prob, error);
  if (src.empty())
    return false;
  return detail::elem_write_file(path, src, error);
}

} // namespace kernscope::tune
