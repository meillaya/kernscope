//===- reduction_gen.cpp - axis-0 reduction template generator ------------===//
//
// Implementation of kernscope::tune::reduction_gen (todo 26). Emits a
// single-source portable .hip kernel for the leading-axis sum reduction
// y[j] = sum_i x[i,j] (fp32 accumulate, bf16 out) matching the golden
// reference (refs.reduction) and validates every candidate PRE-COMPILE
// (search-space membership, arch existence, block limit, cols % vec_width
// divisibility) with a reason string.
//
// Each block reduces vec_width columns (grid = cols / vec_width); the row
// loop is block-strided over the leading axis with a per-access bound check
// (any positive row count is valid). The `mode` dimension selects the
// combine: kStrided = warp-shuffle butterfly with column-aware offsets
// (multiples of vec_width — a __shfl_xor by a multiple of vec_width
// preserves the lane's column residue) + one cross-warp smem combine;
// kTree = shared-memory halving tree with the same column-aware offsets.
//
//===----------------------------------------------------------------------===//

#include "kernscope/tune/reduction_gen.h"

#include <sstream>

namespace kernscope::tune {

ConfigVerdict validate_config(const ReductionConfig &cfg,
                              const ElemProblem &prob) noexcept {
  if (cfg.mode != ElemMode::kStrided && cfg.mode != ElemMode::kTree)
    return {false, "reduction: mode must be strided (warp-shuffle combine) "
                   "or tree (shared-memory tree combine)"};
  ConfigVerdict v = detail::elem_common_validate(
      "reduction", cfg.block, cfg.vec_width, prob.arch, prob.rows, prob.cols);
  if (!v.valid)
    return v;
  if (prob.cols % cfg.vec_width != 0)
    return {false, "reduction: cols (" + std::to_string(prob.cols) +
                       ") not divisible by vec_width (" +
                       std::to_string(cfg.vec_width) +
                       "): each block's column set must be exact (unguarded)"};
  return {true, ""};
}

LaunchGeometry launch_geometry(const ReductionConfig &cfg,
                               const ElemProblem &prob) noexcept {
  LaunchGeometry g;
  g.grid_x = static_cast<int>(prob.cols / cfg.vec_width);
  g.block_x = cfg.block;
  return g;
}

std::string kernel_symbol(const ReductionConfig &cfg) {
  std::string sym = "kernscope_tune_reduction_b";
  sym += std::to_string(cfg.block);
  sym += "_v" + std::to_string(cfg.vec_width);
  sym += std::string("_") + elem_mode_name(cfg.mode);
  return sym;
}

std::string generate_source(const ReductionConfig &cfg,
                            const ElemProblem &prob, std::string *error) {
  const ConfigVerdict verdict = validate_config(cfg, prob);
  if (!verdict.valid) {
    if (error)
      *error = "invalid reduction config: " + verdict.reason;
    return "";
  }

  const std::string symbol = kernel_symbol(cfg);
  const bool strided = (cfg.mode == ElemMode::kStrided);

  std::ostringstream out;
  out << "//===- " << symbol
      << ".hip - axis-0 reduction template (GENERATED) -===//\n"
         "//\n"
         "// GENERATED by kernscope::tune reduction generator (todo 26) — do "
         "not edit.\n"
         "// Config: block="
      << cfg.block << " vec_width=" << cfg.vec_width << " mode="
      << elem_mode_name(cfg.mode) << ".\n"
         "//\n"
         "// y[j] = sum_i x[i,j] over axis 0 (fp32 accumulate, bf16 out),\n"
         "// matching tests/golden refs.reduction. Each block reduces "
         "vec_width\n"
         "// columns (grid = cols / vec_width); the row loop is block-strided\n"
         "// with a per-access bound check, so any positive row count is "
         "valid.\n"
         "// Combine strategy: "
      << (strided ? "warp-shuffle butterfly (column-aware __shfl_xor offsets)"
                  : "shared-memory halving tree")
      << ".\n"
         "// Single-source portable convention (kernels/templates, todo 24):\n"
         "// nvcc -x cu (sm_80/sm_90) AND hipcc (gfx1101).\n"
         "//\n"
         "//===----------------------------------------------------------------------===//\n"
         "\n"
         "#include \"kernscope/kernel_traits.h\"\n"
         "\n"
         "namespace {\n"
         "constexpr int kVec = "
      << cfg.vec_width << ";          // columns per block\n"
         "// Portable warp-shuffle (HIP 2-arg vs CUDA _sync forms).\n"
         "#if defined(__HIP_PLATFORM_AMD__)\n"
         "#define KERNSCOPE_SHFL_XOR(v, off) __shfl_xor((v), (off))\n"
         "#else\n"
         "#define KERNSCOPE_SHFL_XOR(v, off) \\\n"
         "  __shfl_xor_sync(0xffffffffu, (v), (off))\n"
         "#endif\n"
         "\n"
         "__shared__ float ks_sred[1024];  // combine buffer\n"
         "\n";

  if (strided) {
    out << "// Butterfly over the 32 lanes; only offsets that are multiples\n"
           "// of kVec are combined — a __shfl_xor by a multiple of kVec\n"
           "// preserves the lane's column residue (lane % kVec), so every\n"
           "// column's partials combine within their own column and the\n"
           "// total lands on lane c for column c.\n"
           "inline __device__ void ks_shfl_combine(float &v) {\n"
           "  for (int off = 16; off >= 1; off >>= 1)\n"
           "    if (off % kVec == 0) v += KERNSCOPE_SHFL_XOR(v, off);\n"
           "}\n"
           "\n";
  }

  out << "} // namespace\n"
         "\n"
         "extern \"C\" __global__ void " << symbol
      << "(const ks_bf16 *x, ks_bf16 *out, int rows, int cols) {\n"
         "  const int tid = threadIdx.x;\n"
         "  const int c = tid % kVec;              // this thread's column\n"
         "  const int lane_grp = tid / kVec;       // row stride group\n"
         "  const int tpc = blockDim.x / kVec;     // threads per column\n"
         "\n"
         "  // Block-strided row accumulation (bounds-checked: rows may not\n"
         "  // divide tpc). Consecutive threads read adjacent columns of the\n"
         "  // same row -> coalesced.\n"
         "  float acc = 0.0f;\n"
         "  for (int r = lane_grp; r < rows; r += tpc)\n"
         "    acc += ks_bf16_to_float(x[r * cols + c]);\n";

  if (strided) {
    out << "\n"
           "  // Column-aware warp-shuffle butterfly.\n"
           "  ks_shfl_combine(acc);\n"
           "  const int warp = tid >> 5;\n"
           "  const int lane = tid & 31;\n"
           "  if (lane < kVec) ks_sred[warp * kVec + lane] = acc;\n"
           "  __syncthreads();\n"
           "  const int nw = (blockDim.x + 31) >> 5;\n"
           "  float r = 0.0f;\n"
           "  if (warp == 0) {\n"
           "    // Cross-warp combine: the warps' column partials sit at\n"
           "    // indices {w*kVec + c}; every 32nd index preserves the\n"
           "    // column residue (32 % kVec == 0), so each lane gathers its\n"
           "    // own column's partials from all warps (<= 4 smem loads for\n"
           "    // nw <= 32, kVec <= 4) and the butterfly finishes the job.\n"
           "    for (int j = lane; j < nw * kVec; j += 32) r += ks_sred[j];\n"
           "    ks_shfl_combine(r);\n"
           "    if (lane < kVec) ks_sred[lane] = r;\n"
           "  }\n"
           "  __syncthreads();\n"
           "  if (tid < kVec)\n"
           "    out[blockIdx.x * kVec + tid] =\n"
           "        ks_float_to_bf16(ks_sred[tid]);\n";
  } else {
    out << "\n"
           "  // Shared-memory halving tree; offsets from block/2 down to\n"
           "  // kVec are all multiples of kVec (block >= 128, kVec <= 4), so\n"
           "  // every pair stays inside one column.\n"
           "  ks_sred[tid] = acc;\n"
           "  __syncthreads();\n"
           "  for (int off = blockDim.x >> 1; off >= kVec; off >>= 1) {\n"
           "    if (tid < off) ks_sred[tid] += ks_sred[tid + off];\n"
           "    __syncthreads();\n"
           "  }\n"
           "  if (tid < kVec)\n"
           "    out[blockIdx.x * kVec + tid] =\n"
           "        ks_float_to_bf16(ks_sred[tid]);\n";
  }

  out << "}\n";

  return out.str();
}

bool generate_to_file(const ReductionConfig &cfg, const ElemProblem &prob,
                      const std::string &path, std::string *error) {
  const std::string src = generate_source(cfg, prob, error);
  if (src.empty())
    return false;
  return detail::elem_write_file(path, src, error);
}

} // namespace kernscope::tune
