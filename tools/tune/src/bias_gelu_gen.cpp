//===- bias_gelu_gen.cpp - bias+GELU template generator -------------------===//
//
// Implementation of kernscope::tune::bias_gelu_gen (todo 26). Emits a
// single-source portable .hip kernel for the fused bias+GELU elementwise op
// and validates every candidate PRE-COMPILE (search-space membership, arch
// existence, block limit, cols % vec_width divisibility) with a reason
// string — never a broken compile.
//
// The generated kernel reproduces the golden pipeline (refs.bias_gelu) step
// for step: bf16 x and bias, fp32 add, bf16 round of the fused sum, then the
// EXACT erf GELU 0.5*t*(1+erf(t/sqrt(2))) in fp32, bf16 output.
//
//===----------------------------------------------------------------------===//

#include "kernscope/tune/bias_gelu_gen.h"

#include <cmath>
#include <sstream>

namespace kernscope::tune {

namespace {
constexpr double kInvSqrt2 = 0.7071067811865476;  // 1/sqrt(2), refs.py L41
} // namespace

ConfigVerdict validate_config(const BiasGeluConfig &cfg,
                              const ElemProblem &prob) noexcept {
  ConfigVerdict v = detail::elem_common_validate(
      "bias_gelu", cfg.block, cfg.vec_width, prob.arch, prob.rows, prob.cols);
  if (!v.valid)
    return v;
  if (prob.cols % cfg.vec_width != 0)
    return {false, "bias_gelu: cols (" + std::to_string(prob.cols) +
                       ") not divisible by vec_width (" +
                       std::to_string(cfg.vec_width) +
                       "): vector-width divisibility rule"};
  return {true, ""};
}

LaunchGeometry launch_geometry(const BiasGeluConfig &cfg,
                               const ElemProblem &prob) noexcept {
  LaunchGeometry g;
  const std::int64_t total = prob.rows * prob.cols;
  const std::int64_t per_block =
      static_cast<std::int64_t>(cfg.block) * cfg.vec_width;
  g.grid_x = static_cast<int>((total + per_block - 1) / per_block);
  g.block_x = cfg.block;
  return g;
}

std::string kernel_symbol(const BiasGeluConfig &cfg) {
  std::string sym = "kernscope_tune_bias_gelu_b";
  sym += std::to_string(cfg.block);
  sym += "_v" + std::to_string(cfg.vec_width);
  return sym;
}

std::string generate_source(const BiasGeluConfig &cfg,
                            const ElemProblem &prob, std::string *error) {
  const ConfigVerdict verdict = validate_config(cfg, prob);
  if (!verdict.valid) {
    if (error)
      *error = "invalid bias_gelu config: " + verdict.reason;
    return "";
  }

  const std::string symbol = kernel_symbol(cfg);
  char inv_sqrt2_buf[32];
  std::snprintf(inv_sqrt2_buf, sizeof(inv_sqrt2_buf), "%.17g", kInvSqrt2);

  std::ostringstream out;
  out << "//===- " << symbol
      << ".hip - fused bias+GELU template (GENERATED) -===//\n"
         "//\n"
         "// GENERATED by kernscope::tune bias_gelu generator (todo 26) — do "
         "not edit.\n"
         "// Config: block="
      << cfg.block << " vec_width=" << cfg.vec_width << ".\n"
         "//\n"
         "// y[i] = GELU(x[i] + bias[i % cols]) with the EXACT erf GELU\n"
         "// 0.5*t*(1+erf(t/sqrt(2))) matching the golden reference\n"
         "// (tests/golden refs.bias_gelu — NOT the tanh approximation). The\n"
         "// fusion point (x+bias) is computed in fp32 after both operands\n"
         "// are bf16-rounded and the sum is bf16-rounded before the erf, "
         "exactly\n"
         "// like the reference pipeline. bf16 in, fp32 accumulate, bf16 "
         "out.\n"
         "// Single-source portable convention (kernels/templates, todo 24):\n"
         "// nvcc -x cu (sm_80/sm_90) AND hipcc (gfx1101).\n"
         "//\n"
         "//===----------------------------------------------------------------------===//\n"
         "\n"
         "#include \"kernscope/kernel_traits.h\"\n"
         "\n"
         "namespace {\n"
         "constexpr int kVec = "
      << cfg.vec_width << ";          // elements per thread\n"
         "constexpr float kInvSqrt2 = "
      << inv_sqrt2_buf << "f;  // 1/sqrt(2)\n"
         "} // namespace\n"
         "\n"
         "extern \"C\" __global__ void " << symbol
      << "(const ks_bf16 *x, const ks_bf16 *bias, ks_bf16 *out, int total, "
         "int cols) {\n"
         "  // Bounds-checked elementwise walk; grid covers ceil(total / "
         "(block*kVec)).\n"
         "  const int base = (blockIdx.x * blockDim.x + threadIdx.x) * kVec;\n"
         "  for (int vv = 0; vv < kVec; ++vv) {\n"
         "    const int i = base + vv;\n"
         "    if (i < total) {\n"
         "      // Golden pipeline: fp32 add of the bf16 operands, the fused\n"
         "      // sum bf16-rounded at the fusion point (refs.py L76-78), then\n"
         "      // the exact-erf GELU in fp32.\n"
         "      const float s = ks_bf16_to_float(x[i]) +\n"
         "                      ks_bf16_to_float(bias[i % cols]);\n"
         "      const float t = ks_bf16_to_float(ks_float_to_bf16(s));\n"
         "      out[i] = ks_float_to_bf16(\n"
         "          0.5f * t * (1.0f + erff(t * kInvSqrt2)));\n"
         "    }\n"
         "  }\n"
         "}\n";

  return out.str();
}

bool generate_to_file(const BiasGeluConfig &cfg, const ElemProblem &prob,
                      const std::string &path, std::string *error) {
  const std::string src = generate_source(cfg, prob, error);
  if (src.empty())
    return false;
  return detail::elem_write_file(path, src, error);
}

} // namespace kernscope::tune
